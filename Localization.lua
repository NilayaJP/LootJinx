local function lookup(key)
    local e = S[key]
    if not e then return key end
    return e[lang] or e.en or key
end

function LJ.L(key, ...)
    local text = lookup(key)
    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, text, ...)
        if ok then return formatted end
    end
    return text
end


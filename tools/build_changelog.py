"""Generate the in-game release notes and optionally package the addon."""

import argparse
from pathlib import Path
import re
from tempfile import NamedTemporaryFile
from zipfile import ZIP_DEFLATED, ZipFile


ROOT = Path(__file__).resolve().parents[1]
VERSION = r"\d+\.\d+\.\d+"
FOREVERDB_CREDIT = "[Data from ForeverDB.net](https://foreverdb.net)"
DUNGEON_JOURNAL_CREDIT = "[DungeonJournal by ExehnTV](https://www.curseforge.com/wow/addons/dungeonjournal)"
ASSETS = ("LootJinxIcon", "NeedRolls", "NoLoot", "NoNeedWin", "SinceNeedWin")
THEMES = ("Classic", "Journal", "Goblin", "Dwarven", "Oracle")
THEME_ASSETS = tuple(f"Media/Themes/{theme}{variant}.tga" for theme in THEMES for variant in ("Banner", "Icon"))


def release_notes(markdown, version):
    headings = list(re.finditer(r"^##[ \t]+(.+)$", markdown, re.MULTILINE))
    section = re.compile(rf"{re.escape(version)}(?:\s+-\s+(\d{{4}}-\d{{2}}-\d{{2}}))?")
    matches = [
        (index, match)
        for index, heading in enumerate(headings)
        if (match := section.fullmatch(heading[1].strip()))
    ]
    if len(matches) != 1:
        raise ValueError(f"expected one changelog heading for {version}")
    index, match = matches[0]
    end = headings[index + 1].start() if index + 1 < len(headings) else len(markdown)
    sections = []
    title, lines = "", []
    for line in markdown[headings[index].end():end].strip().splitlines():
        attribution = line.strip().rstrip(".")
        if attribution in (FOREVERDB_CREDIT, DUNGEON_JOURNAL_CREDIT):
            continue
        heading = re.fullmatch(r"###[ \t]+(.+)", line.strip())
        if heading:
            body = "\n".join(lines).strip()
            if body:
                sections.append((title, body))
            title, lines = heading[1].strip().rstrip(":").replace("|", "||"), []
            continue
        line = re.sub(r"\[([^\]\n]+)\]\((https?://[^)\s]+)\)", r"\1 (\2)", line)
        line = re.sub(r"^(\s*)[-*]\s+", r"\1• ", line)
        lines.append(line.replace("**", "").replace(chr(96), "").replace("|", "||"))
    body = "\n".join(lines).strip()
    if body:
        sections.append((title, body))
    if not sections:
        raise ValueError(f"empty release notes for {version}")
    return match[1] or "", sections


def lua_text(text):
    equals = ""
    while f"]{equals}]" in text + f"]{equals}":
        equals += "="
    return f"[{equals}[{text}]{equals}]"


def render_changelog(markdown, version):
    date, sections = release_notes(markdown, version)
    entries = "".join(
        f"        {{ title = {lua_text(title)}, text = {lua_text(body)} }},\n"
        for title, body in sections
    )
    return (
        "-- Generated by tools/build_changelog.py from docs/CHANGELOG.md.\n"
        "local _, LJ = ...\n"
        "LJ.ChangelogData = {\n"
        f'    version = "{version}",\n'
        f'    date = "{date}",\n'
        "    sections = {\n"
        f"{entries}"
        "    },\n"
        "}\n"
    )


def build(root, package=False, check=False):
    toc = (root / "LootJinx.toc").read_text(encoding="utf-8-sig")
    match = re.search(rf"^## Version:\s*({VERSION})\s*$", toc, re.MULTILINE)
    if not match:
        raise ValueError("LootJinx.toc must declare a numeric release version")
    version = match[1]
    source = root / "docs" / "CHANGELOG.md"
    output = root / "ChangelogData.lua"
    if package and not source.is_file():
        committed = output.read_text(encoding="utf-8")
        declared = re.search(rf'^LJ\.ChangelogData = \{{\n    version = "({VERSION})",$', committed, re.MULTILINE)
        if not declared or declared[1] != version:
            raise ValueError(f"{output.name} does not match LootJinx.toc version {version}")
    else:
        generated = render_changelog(source.read_text(encoding="utf-8-sig"), version)
        if check:
            if output.read_text(encoding="utf-8") != generated:
                raise ValueError(f"{output.name} is stale; run tools/build_changelog.py")
            return output
        output.write_text(generated, encoding="utf-8", newline="\n")
    if not package:
        return output
    modules = re.findall(r"^([A-Za-z][A-Za-z0-9_]*\.lua)$", toc, re.MULTILINE)
    if "ChangelogData.lua" not in modules or "Changelog.lua" not in modules:
        raise ValueError("LootJinx.toc must load both changelog modules")
    if len(modules) != len(set(modules)):
        raise ValueError("LootJinx.toc lists a Lua module more than once")
    files = ["LootJinx.toc", *modules, *(f"Media/{asset}.tga" for asset in ASSETS), *THEME_ASSETS]
    dist = root / "dist"
    dist.mkdir(exist_ok=True)
    output = dist / f"LootJinx-{version}.zip"
    with NamedTemporaryFile(dir=dist, suffix=".zip", delete=False) as handle:
        temporary = Path(handle.name)
    try:
        with ZipFile(temporary, "w", compression=ZIP_DEFLATED) as archive:
            for name in files:
                archive.write(root / name, f"LootJinx/{name}")
        with ZipFile(temporary) as archive:
            if archive.testzip() or archive.namelist() != [f"LootJinx/{name}" for name in files]:
                raise ValueError("release archive verification failed")
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--zip", action="store_true", help="package the addon and regenerate the notes if Markdown is available")
    mode.add_argument("--check", action="store_true", help="verify the generated notes without writing")
    args = parser.parse_args()
    try:
        print(build(ROOT, package=args.zip, check=args.check))
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
